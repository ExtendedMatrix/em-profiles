#!/usr/bin/env python3
"""Write core-types.json: the node and edge types of the EM core.

    python tools/core_types.py            # rewrite core-types.json
    python tools/core_types.py --check    # exit 1 when the file names a type the core no longer has

A profile type must be the SPECIES of a core type (SPEC.md §5.11). The
validator reads the core types live from s3dgraphy; this file is the same
list written down for people and for tools that do not have s3dgraphy. It is
never written by hand: this script reads the s3dgraphy it runs with and
records which datamodel versions it read. Rerun it when the core changes.

Moved here from ExtendedMatrix/vocabularies (tools/core_types.py, 0.1), where
it read an s3Dgraphy checkout: it now reads the installed library, the same
the CI installs.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "core-types.json"


def current() -> dict:
    import s3dgraphy
    from s3dgraphy.profiles.core import core_edge_types, core_node_types, core_versions

    nodes = sorted(t for t in core_node_types() if t not in ("None", "unknown"))
    v = core_versions()
    return {
        "_comment": "GENERATED by tools/core_types.py from s3dgraphy — do not edit by hand. "
                    "The runtime node_type and edge_type names of the EM core a profile type may specialise.",
        "source": {"library": "s3dgraphy", "version": getattr(s3dgraphy, "__version__", "unknown"),
                   "nodes": v.get("nodes"), "connections": v.get("connections")},
        "node_types": nodes,
        "edge_types": sorted(core_edge_types()),
    }


def drift(written: dict, now: dict) -> dict:
    """What the written list says that the core no longer has (``gone``: an
    error, a profile could specialise it) and what the core has that the list
    does not say yet (``new``: only stale)."""
    out = {}
    for k in ("node_types", "edge_types"):
        w, n = set(written.get(k) or []), set(now[k])
        out[k] = {"gone": sorted(w - n), "new": sorted(n - w)}
    return out


def main(argv) -> int:
    now = current()
    if "--check" in argv:
        d = drift(json.loads(OUT.read_text(encoding="utf-8")), now)
        gone = [t for k in d for t in d[k]["gone"]]
        new = [t for k in d for t in d[k]["new"]]
        if new:
            print(f"core-types.json is behind the core: {', '.join(new)} (rerun tools/core_types.py)")
        if gone:
            print(f"core-types.json names types the core no longer has: {', '.join(gone)}")
            return 1
        print("core-types.json: no type the core lacks")
        return 0
    OUT.write_text(json.dumps(now, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"{OUT.relative_to(REPO)}: {len(now['node_types'])} node types, {len(now['edge_types'])} edge types "
          f"(nodes {now['source']['nodes']}, connections {now['source']['connections']}, "
          f"s3dgraphy {now['source']['version']})")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
